const routes = pageFiles.map(file => {
  const name = file.replace(/\.tsx?$/, '');
  let routePath = '/' + name.toLowerCase();
  if (name === 'HomePage') routePath = '/';
  else if (name === 'AboutPage') routePath = '/about/';
  else if (name === 'ContactPage') routePath = '/contact/';
  else if (name === 'CaseStudiesPage') routePath = '/case-studies/';
  else if (name === 'CodeArcadePage') routePath = '/arcade/';
  else if (name === 'ToolsHubPage') routePath = '/tools/';
  else if (name === 'ServicesHubPage') routePath = '/services/';
  else if (name === 'WhiteLabelPage') routePath = '/white-label-agency-subcontracting/';
  else if (name === 'BlogHubPage' || name === 'BlogPage') routePath = '/blog/';
  else if (name.endsWith('Page') && name.includes('Tool')) routePath = '/tools/' + name.replace('Page', '').toLowerCase() + '/';
  return { component: name, route: routePath };
});

// Extract tools dynamically
const toolsMatches = [...toolsContent.matchAll(/slug:\s*'([^']+)',\s*name:\s*'([^']+)',\s*category:\s*'([^']+)',[\s\S]*?problemStatement:\s*'([^']+)',[\s\S]*?targetUrl:\s*'([^']+)'/g)];
const crawledTools = toolsMatches.map(m => ({
  slug: m[1],
  name: m[2],
  category: m[3],
  problemStatement: m[4].replace(/'/g, "\\'"),
  targetUrl: m[5]
}));

